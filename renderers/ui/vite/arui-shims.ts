// Vite plugin that lets external mods share the UI's single Svelte runtime and SDK instance.
//
// Mods are bundled with `svelte`, `svelte/*` and `@arui/sdk` as externals, so the browser has to
// resolve those bare specifiers itself. This plugin:
//   1. injects an import map at the very top of index.html mapping every shared specifier to a
//      small shim module under /__arui/shims/;
//   2. generates those shim modules. Each one reads the UI's already loaded module namespace from
//      the global registry (filled by src/lib/runtime/shared-modules.ts) and re-exports every
//      export name. The names are enumerated at build time with esbuild's metafile output.
// It works in `vite dev` (middleware) and in `vite build` (emitted assets).

import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';
import type { Plugin } from 'vite';
import {
	MODULE_REGISTRY_GLOBAL,
	SHARED_SPECIFIERS,
	SHIM_BASE,
	shimFileName
} from '../src/lib/runtime/shared-specifiers.ts';

const uiRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sdkRoot = path.resolve(uiRoot, '../sdk');

/** Workspace sources for the SDK entries (they are TypeScript, not prebuilt). */
const LOCAL_ENTRIES: Record<string, string> = {
	'@arui/sdk': path.join(sdkRoot, 'src/index.ts'),
	'@arui/sdk/ui': path.join(sdkRoot, 'src/ui/index.ts')
};

async function exportNames(spec: string): Promise<string[]> {
	const local = LOCAL_ENTRIES[spec];
	const result = await esbuild.build({
		...(local
			? { entryPoints: [local], packages: 'external', external: ['*.svelte', '*.css'] }
			: {
					stdin: {
						contents: `export * from ${JSON.stringify(spec)};`,
						resolveDir: uiRoot,
						loader: 'js'
					}
				}),
		bundle: true,
		write: false,
		metafile: true,
		format: 'esm',
		platform: 'browser',
		conditions: ['browser', 'svelte'],
		outfile: 'shim-probe.js',
		logLevel: 'silent'
	});
	const output = Object.values(result.metafile!.outputs)[0];
	return output.exports.slice().sort();
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function shimSource(spec: string, names: string[]): string {
	const lines = [
		`// Generated by vite/arui-shims.ts. Re-exports the UI's copy of ${spec}.`,
		`const registry = globalThis[${JSON.stringify(MODULE_REGISTRY_GLOBAL)}];`,
		`if (!registry || !registry[${JSON.stringify(spec)}]) throw new Error(${JSON.stringify(
			`[arui] shared module ${spec} is not registered`
		)});`,
		`const m = await registry[${JSON.stringify(spec)}]();`
	];
	names.forEach((name, i) => {
		const local = `_${i}`;
		const exported = name === 'default' || IDENT.test(name) ? name : JSON.stringify(name);
		lines.push(`const ${local} = m[${JSON.stringify(name)}];`);
		lines.push(`export { ${local} as ${exported} };`);
	});
	return lines.join('\n') + '\n';
}

export function importMapJson(base = SHIM_BASE): string {
	const imports: Record<string, string> = {};
	for (const spec of SHARED_SPECIFIERS) imports[spec] = base + shimFileName(spec);
	return JSON.stringify({ imports }, null, 2);
}

async function generateAll(): Promise<Map<string, string>> {
	const files = new Map<string, string>();
	await Promise.all(
		SHARED_SPECIFIERS.map(async (spec) => {
			const names = await exportNames(spec);
			files.set(shimFileName(spec), shimSource(spec, names));
		})
	);
	return files;
}

export function aruiShims(): Plugin {
	return {
		name: 'arui-shims',
		transformIndexHtml: {
			// Run after Vite injected its own client script so the import map can be placed first.
			order: 'post',
			handler(html) {
				const tag = `<script type="importmap">\n${importMapJson()}\n</script>`;
				return html.replace(/<head([^>]*)>/i, (m) => `${m}\n${tag}`);
			}
		},
		configureServer(server) {
			server.middlewares.use(async (req, res, next) => {
				const url = req.url?.split('?')[0] ?? '';
				if (!url.startsWith(SHIM_BASE)) return next();
				const file = url.slice(SHIM_BASE.length);
				const spec = SHARED_SPECIFIERS.find((s) => shimFileName(s) === file);
				if (!spec) return next();
				try {
					// Regenerated per request so SDK export changes show up without restarting.
					const source = shimSource(spec, await exportNames(spec));
					res.setHeader('Content-Type', 'text/javascript; charset=utf-8');
					res.setHeader('Cache-Control', 'no-store');
					res.setHeader('Access-Control-Allow-Origin', '*');
					res.end(source);
				} catch (err) {
					res.statusCode = 500;
					res.end(String(err));
				}
			});
		},
		async generateBundle() {
			const files = await generateAll();
			for (const [name, source] of files) {
				this.emitFile({
					type: 'asset',
					fileName: SHIM_BASE.slice(1) + name,
					source
				});
			}
		}
	};
}
